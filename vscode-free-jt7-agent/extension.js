async function syncVsCodeSettings(folder, cfg) {
  if (!cfg.syncVsCodeSettings) {
    return;
  }

  const root = folder.uri.fsPath;
  const target =
    cfg.settingsTarget === "workspace"
      ? vscode.ConfigurationTarget.Workspace
      : vscode.ConfigurationTarget.Global;
  const allSettings = vscode.workspace.getConfiguration();
  const updateErrors = [];

  async function safeUpdate(key, value) {
    try {
      await allSettings.update(key, value, target);
    } catch (error) {
      const message = error instanceof Error ? error.message : String(error);
      updateErrors.push(`${key}: ${message}`);
    }
  }

  const copilotFile = asPosixPath(path.join(root, ".github", "copilot-instructions.md"));
  const agentsDir = asPosixPath(path.join(root, ".github", "agents"));
  const skillsIndex = asPosixPath(path.join(root, ".github", "skills", ".skills_index.json"));
  const policyFile = asPosixPath(path.join(root, ".github", "free-jt7-policy.yaml"));
  const modelRouting = asPosixPath(path.join(root, ".github", "free-jt7-model-routing.json"));
  const rawPatch = {
    "github.copilot.chat.codeGeneration.instructions": [{ file: copilotFile }],
    "github.copilot.chat.codeGeneration.useInstructionFiles": true,
    "github.copilot.chat.customInstructionsInSystemMessage": true,
    "chat.agent.enabled": true,
    "chat.agentFilesLocations": { [agentsDir]: true },
    "freejt7.enabled": true,
    "freejt7.integrations.vscode.enabled": true,
    "freejt7.skills.index": skillsIndex,
    "freejt7.policy.file": policyFile,
    "freejt7.models.routing": modelRouting,
    "freejt7.models.ide": "vscode"
  };

  await safeUpdate(
    "github.copilot.chat.codeGeneration.instructions",
    rawPatch["github.copilot.chat.codeGeneration.instructions"]
  );
  await safeUpdate("github.copilot.chat.codeGeneration.useInstructionFiles", true);
  await safeUpdate("github.copilot.chat.customInstructionsInSystemMessage", true);
  await safeUpdate("chat.agent.enabled", true);
  await safeUpdate("freejt7.enabled", true);
  await safeUpdate("freejt7.integrations.vscode.enabled", true);
  await safeUpdate("freejt7.skills.index", skillsIndex);
  await safeUpdate("freejt7.policy.file", policyFile);
  await safeUpdate("freejt7.models.routing", modelRouting);
  await safeUpdate("freejt7.models.ide", "vscode");

  const locationPayload =
    target === vscode.ConfigurationTarget.Workspace
      ? { [agentsDir]: true }
      : (() => {
          const existingLocations = allSettings.get("chat.agentFilesLocations", {});
          return existingLocations && typeof existingLocations === "object"
            ? { ...existingLocations, [agentsDir]: true }
            : { [agentsDir]: true };
        })();
  await safeUpdate("chat.agentFilesLocations", locationPayload);

  if (target === vscode.ConfigurationTarget.Workspace) {
    const workspaceSettingsFile = path.join(root, ".vscode", "settings.json");
    await mergeJsonFile(workspaceSettingsFile, rawPatch);
  }

  if (target === vscode.ConfigurationTarget.Global && process.env.APPDATA) {
    const userSettingsFile = path.join(process.env.APPDATA, "Code", "User", "settings.json");
    await mergeJsonFile(userSettingsFile, rawPatch);
  }

  if (updateErrors.length > 0 && cfg.showNotifications) {
    vscode.window.showWarningMessage(
      "Free JT7: some settings were not writable by API, applied JSON fallback."
    );
  }
}

async function provisionWorkspace(outputChannel, manualRun = false, forceOpenClawBoot = false) {
  const folders = vscode.workspace.workspaceFolders || [];
  if (folders.length === 0) {
    if (manualRun) {
      vscode.window.showWarningMessage("Free JT7: no workspace folder is open.");
    }
    return;
  }

  const cfg = getConfig();
  const reports = [];

  for (const folder of folders) {
    try {
      const changes = await provisionFolder(folder, cfg);
      reports.push({ folder: folder.name, changes, ok: true });
    } catch (error) {
      reports.push({
        folder: folder.name,
        changes: [],
        ok: false,
        error: error instanceof Error ? error.message : String(error)
      });
    }
  }

  try {
    await syncVsCodeSettings(folders[0], cfg);
  } catch (error) {
    reports.push({
      folder: folders[0].name,
      changes: [],
      ok: false,
      error: error instanceof Error ? error.message : String(error)
    });
  }

  if (forceOpenClawBoot) {
    openClawBootAttempted = false;
  }

  try {
    const openClawResult = await ensureOpenClawGateway(folders[0], cfg, outputChannel);
    if (!openClawResult.ok && cfg.showNotifications) {
      vscode.window.showWarningMessage(
        `Free JT7 OpenClaw: ${openClawResult.error || openClawResult.reason}`
      );
    }
  } catch (error) {
    const message = error instanceof Error ? error.message : String(error);
    outputChannel.appendLine(`[OpenClaw] fatal error: ${message}`);
    if (cfg.showNotifications) {
      vscode.window.showWarningMessage(`Free JT7 OpenClaw error: ${message}`);
    }
  }

  if (!cfg.showNotifications) {
    return;
  }

  const failures = reports.filter((r) => !r.ok);
  const updated = reports.filter((r) => r.ok && r.changes.length > 0);

  if (failures.length > 0) {
    const first = failures[0];
    vscode.window.showErrorMessage(
      `Free JT7: provisioning error in ${first.folder}: ${first.error}`
    );
    return;
  }

  if (updated.length > 0) {
    const details = updated.map((r) => `${r.folder} (${r.changes.join(", ")})`).join("; ");
    vscode.window.showInformationMessage(`Free JT7 active: ${details}`);
    return;
  }

  if (manualRun) {
    vscode.window.showInformationMessage("Free JT7: files already present, nothing changed.");
  }
}

function activate(context) {
  const outputChannel = vscode.window.createOutputChannel("Free JT7 Agent");
  context.subscriptions.push(outputChannel);

  const runCommand = vscode.commands.registerCommand("freeJt7Agent.provisionNow", async () => {
    await provisionWorkspace(outputChannel, true, false);
  });
  context.subscriptions.push(runCommand);

  const openClawCommand = vscode.commands.registerCommand("freeJt7Agent.startOpenClawNow", async () => {
    await provisionWorkspace(outputChannel, true, true);
  });
  context.subscriptions.push(openClawCommand);

  const cfg = getConfig();
  if (cfg.autoProvision) {
    provisionWorkspace(outputChannel, false, false);
  }

  const folderWatcher = vscode.workspace.onDidChangeWorkspaceFolders(() => {
    const current = getConfig();
    if (current.autoProvision) {
      provisionWorkspace(outputChannel, false, false);
    }
  });
  context.subscriptions.push(folderWatcher);

  const configWatcher = vscode.workspace.onDidChangeConfiguration((event) => {
    if (event.affectsConfiguration("freeJt7Agent")) {
      const current = getConfig();
      if (current.autoProvision) {
        provisionWorkspace(outputChannel, false, false);
      }
    }
  });
  context.subscriptions.push(configWatcher);
}

function deactivate() {}

module.exports = {
  activate,
  deactivate
};
