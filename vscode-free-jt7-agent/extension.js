function runShellCommand(command, cwd, timeoutMs) {
  return new Promise((resolve, reject) => {
    exec(
      command,
      {
        cwd,
        timeout: timeoutMs,
        windowsHide: true,
        maxBuffer: 8 * 1024 * 1024
      },
      (error, stdout, stderr) => {
        if (error) {
          const enriched = new Error(
            `${error.message}\nstdout:\n${stdout || ""}\nstderr:\n${stderr || ""}`
          );
          reject(enriched);
          return;
        }
        resolve({ stdout: stdout || "", stderr: stderr || "" });
      }
    );
  });
}

function sleep(ms) {
  return new Promise((resolve) => setTimeout(resolve, ms));
}

function probeTcpPort(port, host = "127.0.0.1", timeoutMs = 1200) {
  return new Promise((resolve) => {
    const socket = new net.Socket();
    let settled = false;

    const done = (ok) => {
      if (!settled) {
        settled = true;
        socket.destroy();
        resolve(ok);
      }
    };

    socket.setTimeout(timeoutMs);
    socket.once("connect", () => done(true));
    socket.once("timeout", () => done(false));
    socket.once("error", () => done(false));
    socket.connect(port, host);
  });
}

async function readGatewayPortFromConfig(managerRoot) {
  const configPath = path.join(managerRoot, ".openclaw", "openclaw.json");
  try {
    const raw = await fs.readFile(configPath, "utf8");
    const cleaned = raw.replace(/^\uFEFF/, "");
    const cfg = JSON.parse(cleaned);
    const port = Number(cfg?.gateway?.port);
    if (Number.isFinite(port) && port > 0) {
      return port;
    }
  } catch {
    // ignore and fallback to default
  }
  return 18789;
}

async function startOpenClawDetached(managerRoot, outputChannel) {
  const entryCandidates = [
    path.join(managerRoot, "OPEN CLAW", "openclaw.mjs"),
    path.join(managerRoot, "openclaw.mjs")
  ];
  let entry = "";
  for (const candidate of entryCandidates) {
    if (await fileExists(candidate)) {
      entry = candidate;
      break;
    }
  }
  if (!entry) {
    return { ok: false, error: "No se encontro openclaw.mjs para arranque detached." };
  }

  const configPath = path.join(managerRoot, ".openclaw", "openclaw.json");
  const stateDir = path.join(managerRoot, ".openclaw", "state");
  const port = await readGatewayPortFromConfig(managerRoot);

  const child = spawn("node", [entry, "gateway", "--port", String(port)], {
    cwd: managerRoot,
    detached: true,
    stdio: "ignore",
    windowsHide: true,
    env: {
      ...process.env,
      OPENCLAW_CONFIG_PATH: configPath,
      OPENCLAW_STATE_DIR: stateDir
    }
  });
  child.unref();
  outputChannel.appendLine(
    `[OpenClaw] detached start launched (pid=${child.pid || "unknown"}, port=${port})`
  );

  for (let i = 0; i < 12; i += 1) {
    if (await probeTcpPort(port)) {
      return { ok: true, port };
    }
    await sleep(1000);
  }
  return { ok: false, error: `Gateway no escucho en puerto ${port} tras arranque detached.` };
}

async function resolveOpenClawProjectRoot(workspaceRoot, cfg) {
  const candidates = [];

  if (cfg.openClawProjectPath && String(cfg.openClawProjectPath).trim()) {
    candidates.push(String(cfg.openClawProjectPath).trim());
  }

  if (cfg.openClawAutoDetectWorkspaceManager) {
    candidates.push(workspaceRoot);
  }

  if (process.env.FREE_JT7_OPENCLAW_PROJECT) {
    candidates.push(process.env.FREE_JT7_OPENCLAW_PROJECT);
  }

  for (const raw of candidates) {
    const candidate = path.resolve(raw);
    const marker = path.join(candidate, "skills_manager.py");
    if (await fileExists(marker)) {
      return candidate;
    }
  }

  return "";
}

async function ensureOpenClawGateway(folder, cfg, outputChannel) {
  if (!cfg.openClawAutoStart) {
    return { ok: true, skipped: true, reason: "disabled" };
  }

  if (openClawBootAttempted) {
    return { ok: true, skipped: true, reason: "already-attempted" };
  }
  openClawBootAttempted = true;

  const workspaceRoot = folder.uri.fsPath;
  const managerRoot = await resolveOpenClawProjectRoot(workspaceRoot, cfg);

  if (!managerRoot) {
    return {
      ok: false,
      skipped: true,
      reason: "no-skills-manager",
      error:
        "No se encontro skills_manager.py. Configura freeJt7Agent.openClawProjectPath o FREE_JT7_OPENCLAW_PROJECT."
    };
  }

  const statusCmd = String(cfg.openClawStatusCommand || "").trim();
  const startCmd = String(cfg.openClawStartCommand || "").trim();

  outputChannel.appendLine(`[OpenClaw] manager root: ${managerRoot}`);

  if (statusCmd) {
    try {
      const status = await runShellCommand(statusCmd, managerRoot, cfg.openClawCommandTimeoutMs);
      const statusOutput = `${status.stdout}\n${status.stderr}`.toLowerCase();
      outputChannel.appendLine(`[OpenClaw] status command: ${statusCmd}`);
      outputChannel.appendLine(`[OpenClaw] status output:\n${status.stdout}${status.stderr}`);

      const looksRunning =
        /(running|online|activo|healthy|ok)/.test(statusOutput) &&
        !/(not running|detenido|stopped|down|error)/.test(statusOutput);
      if (looksRunning) {
        return { ok: true, started: false, reason: "already-running" };
      }
    } catch (error) {
      outputChannel.appendLine(
        `[OpenClaw] status error: ${error instanceof Error ? error.message : String(error)}`
      );
    }
  }

  if (!startCmd) {
    return { ok: false, skipped: true, reason: "empty-start-command", error: "openClawStartCommand vacio." };
  }

  try {
    const started = await runShellCommand(startCmd, managerRoot, cfg.openClawCommandTimeoutMs);
    outputChannel.appendLine(`[OpenClaw] start command: ${startCmd}`);
    outputChannel.appendLine(`[OpenClaw] start output:\n${started.stdout}${started.stderr}`);
    return { ok: true, started: true, reason: "started" };
  } catch (error) {
    outputChannel.appendLine(
      `[OpenClaw] start command failed, using detached fallback: ${
        error instanceof Error ? error.message : String(error)
      }`
    );
    const detached = await startOpenClawDetached(managerRoot, outputChannel);
    if (detached.ok) {
      return { ok: true, started: true, reason: "started-detached" };
    }
    return { ok: false, reason: "start-failed", error: detached.error };
  }
}

