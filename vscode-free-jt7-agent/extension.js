function asPosixPath(rawPath) {
  return rawPath.replace(/\\/g, "/");
}

async function fileExists(filePath) {
  try {
    await fs.access(filePath);
    return true;
  } catch {
    return false;
  }
}

async function writeFileIfNeeded(filePath, content, overwrite) {
  const exists = await fileExists(filePath);
  if (exists && !overwrite) {
    return { written: false, skipped: true };
  }

  await fs.mkdir(path.dirname(filePath), { recursive: true });
  await fs.writeFile(filePath, content, "utf8");
  return { written: true, skipped: false };
}

async function loadJsonFile(filePath) {
  try {
    const raw = await fs.readFile(filePath, "utf8");
    return JSON.parse(raw);
  } catch {
    return {};
  }
}

async function mergeJsonFile(filePath, patchData) {
  const current = await loadJsonFile(filePath);
  const merged = { ...current, ...patchData };
  await fs.mkdir(path.dirname(filePath), { recursive: true });
  await fs.writeFile(filePath, `${JSON.stringify(merged, null, 4)}\n`, "utf8");
}

